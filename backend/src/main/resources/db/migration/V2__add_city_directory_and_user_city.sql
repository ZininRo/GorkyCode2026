-- City directory for registration/profile. V1 has already been applied in existing environments,
-- so this change is intentionally additive and backward compatible.
CREATE TABLE cities (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(120) NOT NULL,
    region VARCHAR(120),
    country_code CHAR(2) NOT NULL,
    sort_order INTEGER NOT NULL DEFAULT 1000
);

CREATE UNIQUE INDEX ux_cities_identity
    ON cities (lower(name), coalesce(lower(region), ''), country_code);
CREATE INDEX ix_cities_name_prefix
    ON cities (lower(name) varchar_pattern_ops);

